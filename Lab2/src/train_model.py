"""Stage 1: train a random forest on this run's training sample.

Usage (from the Lab2 folder):
    python -m src.train_model --timestamp 20261012120000 --n-samples 2000 --seed 1
"""
import argparse

import joblib
import mlflow
import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, f1_score

from src.data import ARTIFACTS_DIR, LAB_DIR, load_training_data


def train(n_samples, seed):
    X_train, X_cal, y_train, y_cal = load_training_data(n_samples, seed)
    model = RandomForestClassifier(
        n_estimators=200,
        max_depth=10,
        min_samples_leaf=2,
        random_state=seed,
        n_jobs=-1,
    )
    model.fit(X_train, y_train)
    return model, (X_train, y_train), (X_cal, y_cal)


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--timestamp", required=True, help="Run version, generated by GitHub Actions")
    parser.add_argument("--n-samples", type=int, default=2000)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args(argv)

    print(f"Training model version {args.timestamp} on {args.n_samples} samples (seed={args.seed})")
    model, (X_train, y_train), (X_cal, y_cal) = train(args.n_samples, args.seed)

    ARTIFACTS_DIR.mkdir(exist_ok=True)
    joblib.dump(model, ARTIFACTS_DIR / f"model_{args.timestamp}_raw.joblib", compress=3)
    # The calibration stage runs as a separate CI step, so hand it the split.
    np.savez(ARTIFACTS_DIR / f"calibration_split_{args.timestamp}.npz", X=X_cal, y=y_cal)

    mlflow.set_tracking_uri((LAB_DIR / "mlruns").as_uri())
    mlflow.set_experiment("github-lab2")
    with mlflow.start_run(run_name=f"train_{args.timestamp}"):
        mlflow.log_params({
            "timestamp": args.timestamp,
            "n_samples": args.n_samples,
            "seed": args.seed,
            "n_estimators": model.n_estimators,
            "max_depth": model.max_depth,
        })
        y_pred = model.predict(X_train)
        mlflow.log_metrics({
            "train_accuracy": accuracy_score(y_train, y_pred),
            "train_f1": f1_score(y_train, y_pred),
        })

    print(f"Saved {ARTIFACTS_DIR / f'model_{args.timestamp}_raw.joblib'}")


if __name__ == "__main__":
    main()
